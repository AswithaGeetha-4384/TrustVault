# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases

database_url = urlsplit(os.environ.get('DATABASE_URL', f'sqlite:///{BASE_DIR / "db.sqlite3"}'))
if database_url.scheme in {'postgres', 'postgresql'}:
    database_options = {}
    sslmode = os.environ.get('DATABASE_SSLMODE', 'require' if not DEBUG else '')
    if sslmode:
        database_options['sslmode'] = sslmode
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': unquote(database_url.path.lstrip('/')),
            'USER': unquote(database_url.username or ''),
            'PASSWORD': unquote(database_url.password or ''),
            'HOST': database_url.hostname or '',
            'PORT': database_url.port or '',
            'OPTIONS': database_options,
        }
    }
elif database_url.scheme == 'sqlite':
    sqlite_path = unquote(database_url.path)
    if sqlite_path.startswith('//'):
        database_name = Path(sqlite_path[1:])
    else:
        database_name = BASE_DIR / sqlite_path.lstrip('/')
    DATABASES = {'default': {'ENGINE': 'django.db.backends.sqlite3', 'NAME': database_name}}
else:
    raise ImproperlyConfigured('DATABASE_URL must use sqlite, postgres, or postgresql.')


